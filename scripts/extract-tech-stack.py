#!/usr/bin/env python3
"""Extracts the deployed component tech stack from the Angular prototype.

Writes each logo to crates/diagrams/hiero-deployed/assets/tech/<id>.png and the catalogue to
crates/diagrams/hiero-deployed/src/tech_stack_data.rs. Ids, labels, categories, and order are
kept exactly, so diagrams from the prototype keep their logos.

Usage: python3 -I scripts/extract-tech-stack.py ../arch_hiero/src/app/model/tech-stack.ts
"""
import base64
import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text()
root = pathlib.Path(__file__).resolve().parent.parent
assets = root / "crates/diagrams/hiero-deployed/assets/tech"
assets.mkdir(parents=True, exist_ok=True)

pattern = re.compile(
    r"\{\s*id:\s*'([^']+)',\s*label:\s*'((?:[^'\\]|\\.)*)',\s*category:\s*'([^']+)',\s*icon:\s*'data:image/png;base64,([^']+)',\s*\}",
    re.S,
)
items = pattern.findall(source)
if not items:
    sys.exit("no tech stack items found")

variants = {
    "cloud": "Cloud",
    "operating-system": "OperatingSystem",
    "database": "Database",
    "middleware": "Middleware",
    "framework": "Framework",
    "language": "Language",
    "browser": "Browser",
}

lines = [
    "// Generated by scripts/extract-tech-stack.py from the prototype's model/tech-stack.ts.",
    "// Do not edit by hand.",
    "",
    "use crate::tech_stack::{TechCategory, TechItem};",
    "",
    "/// Every technology, in the order offered: by category, then by name.",
    "pub static TECH_STACK: &[TechItem] = &[",
]
for tech_id, label, category, data in items:
    (assets / f"{tech_id}.png").write_bytes(base64.b64decode(data))
    label = label.replace("\\'", "'").replace("\\", "\\\\").replace('"', '\\"')
    lines += [
        "    TechItem {",
        f'        id: "{tech_id}",',
        f'        label: "{label}",',
        f"        category: TechCategory::{variants[category]},",
        f'        png: include_bytes!("../assets/tech/{tech_id}.png"),',
        "    },",
    ]
lines += ["];", ""]
(root / "crates/diagrams/hiero-deployed/src/tech_stack_data.rs").write_text("\n".join(lines))
print(f"{len(items)} technologies")
